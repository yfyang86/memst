"""Generate the manuscript's tables and the numbers its text cites.

    python manuscript/memst/make_tables.py

Reads the result directories under benchmarks/results/ and writes
manuscript/memst/tables/*.tex. Every figure in the paper's evaluation comes
from here, so re-run it after a new evaluation run and recompile.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "benchmarks" / "results"
OUT = Path(__file__).resolve().parent / "tables"
sys.path.insert(0, str(ROOT))

from benchmarks.harness.route_analysis import analyse  # noqa: E402


def load(name):
    return json.loads((RESULTS / name / "summary.json").read_text())


def rows(name):
    return [json.loads(line) for line in (RESULTS / name / "answers.jsonl").read_text().splitlines() if line.strip()]


def pct(value, digits=1):
    return "--" if value is None else f"{100 * value:.{digits}f}"


def interval(entry, key, low, high):
    return f"{pct(entry[key])} \\,({pct(entry[low])}--{pct(entry[high])})"


def diff(triple):
    if not triple:
        return "--"
    value, low, high = (100 * x for x in triple)
    text = f"${value:+.1f}$ \\,(${low:+.1f}$ to ${high:+.1f}$)"
    # Bold where the interval excludes zero: a difference the data supports.
    return f"\\textbf{{\\boldmath {text}}}" if low > 0 or high < 0 else text


def tt(name):
    return f"\\texttt{{{name}}}"


def table(path, columns, header, body, groups=None):
    """`groups` is an optional line above the header that labels groups of columns."""
    lines = [f"\\begin{{tabular}}{{@{{}}{columns}@{{}}}}", "\\toprule"]
    if groups:
        lines.append(groups)
    lines += [" & ".join(header) + " \\\\", "\\midrule"]
    lines += [" & ".join(row) + " \\\\" if row else "\\midrule" for row in body]
    lines += ["\\bottomrule", "\\end{tabular}"]
    (OUT / path).write_text("% Generated by make_tables.py; do not edit.\n" + "\n".join(lines) + "\n")


def main():
    OUT.mkdir(exist_ok=True)
    numbers = {}

    def number(name, value):
        # TeX command names are letters only.
        numbers["".join(c for c in name if c.isalpha())] = value

    # ---- Full runs ----
    locomo, lme = load("full-locomo"), load("full-longmemeval")
    order = ["full-context", "raw-bm25", "raw-dense", "raw-hybrid", "graph-entities", "graph-facts", "default"]
    for key, summary, answerable in (("locomo", locomo, True), ("longmemeval", lme, False)):
        body = []
        for name in order:
            e = summary["pipelines"][name]
            row = [tt(name), interval(e, "f1", "f1_low", "f1_high"), interval(e, "judged_accuracy", "judged_low", "judged_high")]
            if answerable:
                row.append(pct(e["answerable"]["judged_accuracy"]))
            row += [pct(e["evidence_in_context"]), f"{e['prompt_tokens_mean']:,}", f"{e['write_llm_calls_per_conversation']:.0f}"]
            body.append(row)
            if name in ("full-context", "raw-dense"):
                body.append(None) if name == "full-context" else None
        header = ["Pipeline", "F1", "Judged correct"] + (["Answerable"] if answerable else []) + ["Evidence", "Tokens", "Calls"]
        table(f"full-{key}.tex", "l" + "c" * (len(header) - 1), header, body)

    body = [[tt(n), diff(locomo["paired"][n]["f1"]), diff(locomo["paired"][n]["judged"]), diff(lme["paired"][n]["judged"])]
            for n in order if n != "raw-dense"]
    table("paired-full.tex", "lccc", ["Pipeline", "LoCoMo F1", "LoCoMo judged", "LongMemEval-S judged"], body)

    categories = ["single-hop", "multi-hop", "temporal", "open-domain", "adversarial"]
    body = [[tt(n)] + [pct(locomo["pipelines"][n]["by_category"][c]["judged_accuracy"]) for c in categories] for n in order]
    sizes = [str(locomo["pipelines"]["default"]["by_category"][c]["n"]) for c in categories]
    table("locomo-categories.tex", "lccccc", ["Pipeline"] + [f"{c} ({n})" for c, n in zip(categories, sizes)], body)

    lme_types = [c for c in lme["categories"]]
    body = [[tt(n)] + [pct(lme["pipelines"][n]["by_category"][c]["judged_accuracy"], 0) for c in lme_types] for n in order]
    short = {"single-session-assistant": "assistant", "single-session-preference": "preference", "single-session-user": "user",
             "knowledge-update": "update", "multi-session": "multi-session", "temporal-reasoning": "temporal", "abstention": "abstention"}
    table("longmemeval-categories.tex", "l" + "c" * len(lme_types),
          ["Pipeline"] + [f"{short[c]} ({lme['pipelines']['default']['by_category'][c]['n']})" for c in lme_types], body)

    for prefix, summary in (("Locomo", locomo), ("Lme", lme)):
        for name in order:
            e = summary["pipelines"][name]
            tag = "".join(part.capitalize() for part in name.split("-"))
            number(f"{prefix}{tag}Judged", pct(e["judged_accuracy"]))
            number(f"{prefix}{tag}Fone", pct(e["f1"]))
            number(f"{prefix}{tag}Tokens", f"{e['prompt_tokens_mean']:,}")
        number(f"{prefix}Questions", f"{summary['settings']['questions']:,}")
        number(f"{prefix}HistoryTokens", f"{summary['conversation_tokens_estimate_mean']:,}")
        number(f"{prefix}OracleJudged", pct(summary["oracle_router"]["judged"]))
    number("LocomoAnswerable", f"{locomo['pipelines']['default']['answerable']['n']:,}")
    number("LocomoGraphCalls", f"{locomo['pipelines']['default']['write_llm_calls_per_conversation']:.0f}")
    number("LmeGraphCalls", f"{lme['pipelines']['default']['write_llm_calls_per_conversation']:.0f}")
    d = locomo["paired"]["default"]["judged"]
    number("LocomoDefaultVsDense", f"{-100 * d[0]:.1f}")
    number("LocomoDefaultVsDenseLow", f"{-100 * d[2]:.1f}")
    number("LocomoDefaultVsDenseHigh", f"{-100 * d[1]:.1f}")
    number("LmeEvidenceDense", pct(lme["pipelines"]["raw-dense"]["evidence_in_context"], 0))
    number("LocomoEvidenceDense", pct(locomo["pipelines"]["raw-dense"]["evidence_in_context"]))
    number("LmeTokenRatio", f"{lme['pipelines']['full-context']['prompt_tokens_mean'] / lme['pipelines']['raw-dense']['prompt_tokens_mean']:.0f}")
    temporal = lambda n, k: locomo["pipelines"][n]["by_category"]["temporal"][k]
    number("LocomoTemporalDefaultFone", pct(temporal("default", "f1")))
    number("LocomoTemporalDenseFone", pct(temporal("raw-dense", "f1")))
    number("LocomoTemporalDefaultJudged", pct(temporal("default", "judged_accuracy")))
    number("LocomoTemporalDenseJudged", pct(temporal("raw-dense", "judged_accuracy")))

    # Reader accuracy when the answer turn is, and is not, in the context.
    full_rows = rows("full-locomo")
    for name, tag in (("raw-dense", "Dense"), ("default", "Default")):
        mine = [r for r in full_rows if r["pipeline"] == name and r["evidence_in_context"] is True]
        number(f"LocomoWithEvidence{tag}", pct(sum(r["judged_correct"] for r in mine) / len(mine), 0))
    by_question = {}
    for r in full_rows:
        by_question.setdefault(r["question_id"], []).append(r["judged_correct"])
    number("LocomoNobodyRight", str(sum(1 for v in by_question.values() if max(v) == 0)))

    # ---- Routing ----
    for prefix, name in (("Locomo", "full-locomo"), ("Lme", "full-longmemeval")):
        routed = analyse(rows(name))
        number(f"{prefix}RoutedJudged", pct(routed["routed_score"]))
        number(f"{prefix}BestSingleJudged", pct(routed["best_single_score"]))

    # ---- Read path ----
    read = load("read-path-locomo")
    strict = load("read-path-locomo-pro-judge")
    read_lme = load("read-path-longmemeval")
    names = ["raw-dense", "dense-wide", "dense+neighbors", "rerank", "rerank-strict", "dense-reason", "dense-wide-reason",
             "rerank-reason", "default", "default-reason", "full-context", "full-context-reason"]
    body = []
    for name in names:
        e, s = read["pipelines"][name], strict["pipelines"][name]
        l = read_lme["pipelines"].get(name)
        body.append([tt(name), pct(e["judged_accuracy"]), pct(s["judged_accuracy"]), diff(strict["paired"].get(name, {}).get("judged")) if name != "raw-dense" else "--",
                     f"{e['prompt_tokens_mean']:,}", pct(l["judged_accuracy"]) if l else "--", f"{l['prompt_tokens_mean']:,}" if l else "--"])
    table("read-path.tex", "lcccrcr",
          ["Pipeline", "Judged", "Strict judge", "Strict, vs. \\texttt{raw-dense}", "Tokens", "Judged", "Tokens"], body,
          groups=" & \\multicolumn{4}{c}{LoCoMo pilot} & \\multicolumn{2}{c}{LongMemEval-S pilot} \\\\ \\cmidrule(lr){2-5} \\cmidrule(l){6-7}")
    for name, tag in (("raw-dense", "Dense"), ("dense-wide-reason", "WideReason"), ("rerank-reason", "RerankReason"),
                      ("full-context", "Full"), ("full-context-reason", "FullReason"), ("dense-reason", "DenseReason"), ("default-reason", "DefaultReason")):
        number(f"Read{tag}", pct(read["pipelines"][name]["judged_accuracy"]))
        number(f"Read{tag}Strict", pct(strict["pipelines"][name]["judged_accuracy"]))
        if name in read_lme["pipelines"]:
            number(f"ReadLme{tag}", pct(read_lme["pipelines"][name]["judged_accuracy"]))
    number("ReadQuestions", str(read["settings"]["questions"]))
    number("ReadLmeQuestions", str(read_lme["settings"]["questions"]))

    # ---- The narrower test for the graph ----
    role, role_strict, role_old = load("graph-role-locomo"), load("graph-role-locomo-pro-judge"), load("graph-role-locomo-old-dates")
    role_lme = load("graph-role-longmemeval")
    names = ["dense-wide-reason", "rerank-reason", "wide+sources-reason", "wide+timeline-reason", "wide+facts-reason",
             "default-reason", "sources-only-reason", "timeline-only-reason"]
    what = {
        "dense-wide-reason": "none: 40 raw turns", "rerank-reason": "none: reranked raw turns",
        "wide+sources-reason": "source messages of its facts", "wide+timeline-reason": "facts as a dated timeline",
        "wide+facts-reason": "facts as lines", "default-reason": "facts, sources, 12 raw turns",
        "sources-only-reason": "sources and 12 raw turns", "timeline-only-reason": "timeline and sources only",
    }
    body = []
    for name in names:
        e = role["pipelines"][name]
        l = role_lme["pipelines"].get(name)
        body.append([tt(name), what[name], pct(e["judged_accuracy"]),
                     diff(role["paired"].get(name, {}).get("judged")) if name != "dense-wide-reason" else "--",
                     diff(role_strict["paired"].get(name, {}).get("judged")) if name != "dense-wide-reason" else "--",
                     pct(l["judged_accuracy"]) if l else "--"])
    table("graph-role.tex", "llcccc", ["Pipeline", "The graph adds", "Judged", "Difference", "Difference, strict judge", "LongMemEval-S"], body)
    number("RoleQuestions", str(role["settings"]["questions"]))
    number("RoleLmeQuestions", str(role_lme["settings"]["questions"]))
    number("RoleDefaultDirectOld", pct(role_old["pipelines"]["default"]["judged_accuracy"]))
    number("RoleDefaultDirectNew", pct(role["pipelines"]["default"]["judged_accuracy"]))
    number("RoleWide", pct(role["pipelines"]["dense-wide-reason"]["judged_accuracy"]))
    number("RoleDenseDirect", pct(role["pipelines"]["raw-dense"]["judged_accuracy"]))
    # Paired differences are stored relative to dense-wide-reason; turn the
    # raw-dense one round to read "wide and reasoning, minus direct".
    d = role["paired"]["raw-dense"]["judged"]
    number("RoleWideVsDense", f"{-100 * d[0]:.1f}")
    number("RoleWideVsDenseLow", f"{-100 * d[2]:.1f}")
    number("RoleWideVsDenseHigh", f"{-100 * d[1]:.1f}")
    number("RoleWideVsDenseStrict", f"{-100 * role_strict['paired']['raw-dense']['judged'][0]:.1f}")
    number("RoleLmeWide", pct(role_lme["pipelines"]["dense-wide-reason"]["judged_accuracy"], 0))

    macros = "".join(f"\\newcommand{{\\num{name}}}{{{value}}}\n" for name, value in sorted(numbers.items()))
    (OUT / "numbers.tex").write_text("% Generated by make_tables.py; do not edit.\n" + macros)
    print(f"wrote {len(list(OUT.glob('*.tex')))} files to {OUT}, {len(numbers)} numbers")


if __name__ == "__main__":
    main()
